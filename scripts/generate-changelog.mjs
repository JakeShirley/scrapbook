#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(repoRoot, "apps/web/src/generated/changelog.ts");
const packageJsonPath = join(repoRoot, "package.json");

const appVersion = JSON.parse(readFileSync(packageJsonPath, "utf8")).version ?? "0.0.0";

const moduleSource = (markdown) =>
  `// Generated by scripts/generate-changelog.mjs — do not edit by hand.\n` +
  `export const appVersion = ${JSON.stringify(appVersion)};\n` +
  `export const changelogMarkdown = ${JSON.stringify(markdown)};\n`;

const writeModule = (markdown) => {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, moduleSource(markdown));
};

const hasGitHistory = () => {
  if (!existsSync(join(repoRoot, ".git"))) {
    return false;
  }

  try {
    execFileSync("git", ["rev-parse", "--git-dir"], { cwd: repoRoot, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
};

const placeholderMarkdown = () =>
  `No release history is available in this build. ` +
  `The full changelog is generated from git history at release time.\n`;

const generateFromGit = async () => {
  const { ConventionalChangelog } = await import("conventional-changelog");

  const generator = new ConventionalChangelog(repoRoot)
    .readPackage()
    .loadPreset("angular")
    .options({ releaseCount: 0 })
    .context({ version: appVersion });

  let output = "";
  for await (const chunk of generator.write()) {
    output += chunk;
  }
  return output;
};

const main = async () => {
  if (!hasGitHistory()) {
    if (existsSync(outputPath)) {
      console.log("No git history available; keeping existing changelog module.");
      return;
    }
    console.log("No git history available; writing placeholder changelog module.");
    writeModule(placeholderMarkdown());
    return;
  }

  try {
    const body = (await generateFromGit()).trim();
    const markdown = `${body.length > 0 ? `${body}\n` : "No releases yet.\n"}`;
    writeModule(markdown);
    console.log(`Generated changelog module for v${appVersion}.`);
  } catch (error) {
    console.warn(`Failed to generate changelog from git: ${error?.message ?? error}`);
    if (!existsSync(outputPath)) {
      writeModule(placeholderMarkdown());
    }
  }
};

await main();
